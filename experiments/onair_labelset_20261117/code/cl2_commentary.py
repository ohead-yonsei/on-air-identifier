"""AI commentary demo, step 2: one Korean sentence every 3 s for every race of a day, from the identifier's output and confirmed facts.
See live_commentary/DESIGN_KO.md.  usage: cl2_commentary.py DAY [RACE ...]     (DAY = 20261115)

The commentary system never sees the running-order strip. Two modes, chosen in code:
  leader     the identifier stated numbers, at least 8 s after the start and more than 30 s before the expected finish
  confirmed  every other time point: race facts and elapsed time only (numbers confirmed within the last 9 s may be recalled in the past tense)
Each sentence is checked in code; a sentence that breaks the rules is regenerated once, then replaced by a fixed template.
For comparison a "picture only" sentence is generated by the same model from the masked frame, with no identifier and no check."""
import base64
import bisect
import json
import re
import sys
import time
import urllib.request
from pathlib import Path

import cv2

ROOT = Path(__file__).resolve().parent.parent
args = [a for a in sys.argv[1:] if a != "--v2"]
V2 = "--v2" in sys.argv          # second run: race distance and start time come from race_facts.json (checked by eye), not from the model's reading
day, only = args[0], set(args[1:])
O = ROOT / "live_commentary" / day
FACTS = json.loads((O / "race_facts.json").read_text()) if V2 else {}
SUB = "_v2" if V2 else ""
ENDPOINT, MODEL = "http://127.0.0.1:11435", "qwen3.5:9b"
CAP = {1: "흰색", 2: "노란색", 3: "빨간색", 4: "검정", 5: "파란색", 6: "초록색", 7: "갈색", 8: "분홍색", 9: "보라색", 10: "하늘색", 11: "하늘색 줄무늬"}
MASKS = [(0, 0, 360, 210), (1710, 0, 1920, 180), (0, 930, 1920, 1080)]
HEADER, TIMER = (0, 0, 360, 210), (70, 930, 360, 1055)
PAST = ("조금 전", "앞서", "직전까지", "방금 전")
BANNED = re.compile(r"\d\s*위|선두는|우승|1등|역전|이름")
LEDGER, RAW = O / f"ledger{SUB}.jsonl", O / f"raw{SUB}.jsonl"


def expected_seconds(d):
    return d * (0.062 if d <= 1200 else 0.0635 if d <= 1400 else 0.066)


def ask(messages, schema, seed, temperature, images=None, tag=""):
    if images:
        messages[-1]["images"] = images
    body = json.dumps({"model": MODEL, "messages": messages, "format": schema, "stream": False, "think": False, "keep_alive": "10m",
                       "options": {"temperature": temperature, "seed": seed, "num_ctx": 8192, "num_predict": 160, "top_p": 0.9}}).encode()
    with LEDGER.open("a") as f:
        f.write(json.dumps({"tag": tag, "seed": seed, "temperature": temperature, "messages": [{"role": m["role"], "content": m["content"]} for m in messages],
                            "images": len(images or [])}, ensure_ascii=False) + "\n")
    start = time.perf_counter()
    try:
        with urllib.request.urlopen(urllib.request.Request(ENDPOINT + "/api/chat", data=body, headers={"Content-Type": "application/json"}), timeout=300) as r:
            out = json.loads(json.loads(r.read().decode())["message"]["content"])
        err = None
    except Exception as e:
        out, err = None, repr(e)
    with RAW.open("a") as f:
        f.write(json.dumps({"tag": tag, "out": out, "error": err, "ms": round((time.perf_counter() - start) * 1000)}, ensure_ascii=False) + "\n")
    return out


def png(bgr):
    return base64.b64encode(cv2.imencode(".png", bgr)[1].tobytes()).decode()


def tidy(line):
    """The model writes '3 번', '1 경주', '12 초'; join the number to its unit."""
    return re.sub(r"(\d)\s+(번|경주|초|m\b|미터)", r"\1\2", line.strip())


def numbers_in(line):
    return sorted({int(n) for n in re.findall(r"(\d+)\s*번", line)})


SYSTEM = ("당신은 한국어 경마 중계 캐스터다. 주어진 사실만으로 중계한다. 말 이름, 기수 이름, 순위(1위·2위), 선두가 누구인지, 거리 차이, 우승은 말하지 않는다. "
          "번호는 '4번'처럼 쓰고, 사실에 주어진 번호만 쓴다. 한 문장, 45자 안쪽, 캐스터 말투로 쓴다. JSON으로만 답한다.")
LINE = {"type": "object", "properties": {"line": {"type": "string"}}, "required": ["line"], "additionalProperties": False}


def check(line, mode, allowed, recall):
    if not line or len(line) > 80 or BANNED.search(line):
        return False
    nums = numbers_in(line)
    if mode == "leader":
        return bool(nums) and set(nums) <= set(allowed)
    return set(nums) <= set(recall) and (not nums or any(w in line for w in PAST))


def template(mode, allowed, recall, phase, info, elapsed):
    if mode == "leader":
        return "선두권에는 " + ", ".join(f"{CAP[n]} 모자 {n}번" for n in allowed) + "이 달리고 있습니다."
    if recall:
        return "조금 전까지 선두권은 " + ", ".join(f"{n}번" for n in recall) + "이었습니다."
    return f"{info['place']} {info['race']}경주 {info['distance']}m, {phase}입니다."


summary = []
for res_path in sorted((O / "results").glob("R??.json")):
    race = res_path.stem
    if only and race not in only:
        continue
    res = json.loads(res_path.read_text())
    pts = json.loads(res_path.with_suffix(".pts.json").read_text())
    cap = cv2.VideoCapture(str(O / "videos" / f"{race}.mp4"))

    def grab(t):
        cap.set(cv2.CAP_PROP_POS_FRAMES, bisect.bisect_right(pts, t + 1e-8) - 1)
        return cap.read()[1]

    first = grab(res["points"][0]["t"])
    x1, y1, x2, y2 = HEADER
    head = ask([{"role": "user", "content": "This is the corner graphic of a horse-racing broadcast. Read the race number (the single number next to the place name) and the race distance in metres. Return only JSON."}],
               {"type": "object", "properties": {"race": {"type": "integer"}, "distance_m": {"type": "integer"}}, "required": ["race", "distance_m"], "additionalProperties": False},
               1, 0, [png(first[y1:y2, x1:x2])], f"{race}:header")
    x1, y1, x2, y2 = TIMER
    clock = ask([{"role": "user", "content": "This is the race clock of a horse-racing broadcast, shown as minutes:seconds.tenths (for example 0:20.9). Read it. Return only JSON."}],
                {"type": "object", "properties": {"minutes": {"type": "integer"}, "seconds": {"type": "number"}}, "required": ["minutes", "seconds"], "additionalProperties": False},
                1, 0, [png(first[y1:y2, x1:x2])], f"{race}:clock")
    distance = head["distance_m"] if head and 800 <= head["distance_m"] <= 2400 else None
    start_t = res["points"][0]["t"] - (clock["minutes"] * 60 + clock["seconds"]) if clock else None
    info = {"place": "서울", "race": int(race[1:]), "distance": distance, "race_read": head["race"] if head else None, "clock_read": clock, "start_video_time": start_t}
    if V2:
        distance, start_t = FACTS[race]["distance"], FACTS[race]["start_video_time"]
        info.update(distance=distance, start_video_time=start_t, facts_source="race_facts.json (checked by eye)")
    if distance is None or start_t is None:
        print(race, "could not read the race distance or the clock; skipped", info, flush=True)
        continue
    T = expected_seconds(distance)
    rows, prev_lines, last_leader = [], [], None
    for k, p in enumerate(res["points"]):
        elapsed = p["t"] - start_t
        if V2 and not (0 <= elapsed <= T + 3):
            continue      # second run only: commentate from the start to 3 s after the expected finish
        phase = "출발 직후" if elapsed < 8 else "경주 중반" if elapsed <= T - 30 else "경주 후반" if elapsed <= T - 8 else "결승선 직전" if elapsed <= T + 1 else "결승선 통과 무렵"
        mode = "leader" if p["statements"] and 8 <= elapsed <= T - 30 else "confirmed"
        allowed = p["statements"] if mode == "leader" else []
        recall = last_leader["numbers"] if mode == "confirmed" and last_leader and p["t"] - last_leader["t"] <= 9 else []
        facts = {"경주": f"서울 {info['race']}경주 {distance}m", "출발 뒤 지난 시간": f"{elapsed:.0f}초", "구간": phase}
        left = round(distance * (1 - elapsed / T) / 100) * 100       # estimated from the clock, not measured
        if 100 <= left < distance and elapsed >= 8:
            facts["남은 거리(시계로 어림)"] = f"약 {left}m"
        if mode == "leader":
            facts["지금 선두권에 있는 번호"] = [f"{n}번({CAP[n]} 모자)" for n in allowed]
            if last_leader:
                new = [n for n in allowed if n not in last_leader["numbers"]]
                if new:
                    facts["방금 선두권에 새로 보인 번호"] = [f"{n}번" for n in new]
            rule = "선두권 번호를 한 개 이상 넣어 지금 상황을 한 문장으로 중계하라. 번호들 사이의 순서는 말하지 말고 '선두권'이라고만 하라."
        else:
            if recall:
                facts["조금 전까지 선두권으로 확인된 번호"] = [f"{n}번" for n in recall]
            rule = ("지금 누가 앞서는지는 확인되지 않았다. 지금 앞선 말을 말하지 말고, 경주 정보와 지난 시간, 구간만으로 한 문장을 만들어라. "
                    + ("확인된 번호는 '조금 전까지'라는 과거형으로만 말할 수 있다." if recall else "번호는 쓰지 마라."))
        user = ("사실: " + json.dumps(facts, ensure_ascii=False) + "\n앞의 두 문장: " + json.dumps(prev_lines[-2:], ensure_ascii=False) + "\n지시: " + rule
                + " 앞 문장과 같은 표현은 피하라. 경마장·경주 번호·거리는 첫 문장이 아니면 되풀이하지 마라. 남은 거리를 말할 때는 '약'을 붙여라.")
        line, source = None, "model"
        for attempt in (0, 1):
            out = ask([{"role": "system", "content": SYSTEM}, {"role": "user", "content": user}], LINE, 20261117 + k + 1000 * attempt, 0.5 + 0.2 * attempt, None, f"{race}:{k}:{attempt}")
            cand = tidy(out["line"]) if out and isinstance(out.get("line"), str) else ""
            if check(cand, mode, allowed, recall):
                line, source = cand, "model" if attempt == 0 else "model_retry"
                break
        if line is None:
            line, source = template(mode, allowed, recall, phase, info, elapsed), "template"
        frame = grab(p["t"])
        for mx1, my1, mx2, my2 in MASKS:
            frame[my1:my2, mx1:mx2] = 48
        base = ask([{"role": "system", "content": "당신은 한국어 경마 중계 캐스터다. 화면을 보고 중계한다. 말 번호는 기수의 모자색으로 알 수 있다: 1 흰색, 2 노란색, 3 빨간색, 4 검정, 5 파란색, 6 초록색, 7 갈색, 8 분홍색, 9 보라색, 10 하늘색, 11 이상 하늘색 줄무늬. JSON으로만 답한다."},
                    {"role": "user", "content": f"서울 {info['race']}경주 {distance}m, 출발 뒤 {elapsed:.0f}초의 화면이다. 지금 선두권(앞선 세 마리)에 있는 말을 '4번'처럼 번호로 넣어, 한 문장(45자 안쪽)으로 중계하라."}],
                   LINE, 20261117 + k, 0.5, [png(cv2.resize(frame, (1280, 720), interpolation=cv2.INTER_AREA))], f"{race}:{k}:picture")
        base_line = tidy(base["line"]) if base and isinstance(base.get("line"), str) else ""
        prev_lines.append(line)
        if mode == "leader":
            last_leader = {"t": p["t"], "numbers": allowed}
        rows.append({"k": k, "t": p["t"], "elapsed": round(elapsed, 1), "phase": phase, "mode": mode, "identifier": p["statements"], "allowed": allowed, "recall": recall,
                     "line": line, "source": source, "said_numbers": numbers_in(line), "picture_only_line": base_line, "picture_only_numbers": numbers_in(base_line),
                     "strip": p.get("strip")})
        print(f"{race} {elapsed:5.1f}s [{mode:9s}] {line}   ||  그림만: {base_line}", flush=True)
    cap.release()
    (O / f"commentary{SUB}").mkdir(exist_ok=True)
    (O / f"commentary{SUB}" / f"{race}.json").write_text(json.dumps({"race": race, "info": info, "expected_finish_seconds": round(T, 1), "rows": rows}, ensure_ascii=False, indent=1))
    summary.append((race, len(rows), sum(r["mode"] == "leader" for r in rows), sum(r["source"] == "template" for r in rows)))
print("races", len(summary), summary)
try:
    urllib.request.urlopen(urllib.request.Request(ENDPOINT + "/api/generate", data=json.dumps({"model": MODEL, "keep_alive": 0}).encode(), headers={"Content-Type": "application/json"}), timeout=60).read()
except Exception:
    pass
